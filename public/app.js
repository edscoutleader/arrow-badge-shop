function cleanBadgeStr(str) {
  let s = str
    .toLowerCase()
    .replace(/\blvl\.?\s*/g, " ")
    .replace(/\blevel\s*/g, " ")
    .replace(/[^a-z0-9]/g, " ")
    .replace(/\s+/g, " ")
    .trim();

  // Normalize "hikes 5" to "hikes away 5"
  if (s.startsWith("hikes ") && !s.startsWith("hikes away ")) {
    s = s.replace(/^hikes\s+/, "hikes away ");
  }
  return s;
}

async function handlePdfUpload(e) {
  const file = e.target.files[0];
  if (!file) return;

  const reader = new FileReader();
  reader.onload = async function() {
    const typedarray = new Uint8Array(this.result);
    const pdf = await pdfjsLib.getDocument(typedarray).promise;
    let fullText = "";

    for (let i = 1; i <= pdf.numPages; i++) {
      const page = await pdf.getPage(i);
      const content = await page.getTextContent();
      const strings = content.items.map(item => item.str);
      fullText += strings.join("\n") + "\n";
    }

    parseOsmPdfText(fullText);
  };
  reader.readAsArrayBuffer(file);
}

function parseOsmPdfText(text) {
  const lines = text.split("\n").map(l => l.trim()).filter(Boolean);
  let matchCount = 0;
  let unmatchedBadges = [];
  let detectedSection = "scouts";

  // 1. Detect Group and Section from header (e.g. "4th Eastleigh: Scouts")
  for (let i = 0; i < Math.min(lines.length, 6); i++) {
    const line = lines[i];
    if (line.includes(":")) {
      const parts = line.split(":");
      const grpName = parts[0].trim().toLowerCase();
      const secName = parts[1].trim().toLowerCase();

      const gSelect = document.getElementById("leaderGroup");
      for (let opt of gSelect.options) {
        if (opt.value && opt.value.toLowerCase().includes(grpName)) {
          gSelect.value = opt.value;
          break;
        }
      }

      const sSelect = document.getElementById("leaderSection");
      for (let opt of sSelect.options) {
        if (opt.value && opt.value.toLowerCase().includes(secName)) {
          sSelect.value = opt.value;
          detectedSection = opt.value.toLowerCase();
          break;
        }
      }
    }
  }

  // 2. Parse Badge Rows
  const ignoreWords = [
    'badge', 'required', 'challenge badges', 'activity badges', 
    'staged badges', 'core badges', 'page', 'downloaded', 
    'badge shopping list', 'generated by', 'current stock', 'desired stock'
  ];

  for (let i = 0; i < lines.length - 1; i++) {
    const line = lines[i];
    const nextLine = lines[i + 1];
    const qty = parseInt(nextLine, 10);

    const isOrphanBracket = line.startsWith("(") && line.endsWith(")");

    if (!isNaN(qty) && qty > 0 && isNaN(parseInt(line, 10)) && !ignoreWords.includes(line.toLowerCase()) && !isOrphanBracket) {
      const targetClean = cleanBadgeStr(line);
      
      let candidates = CATALOGUE.filter(b => {
        const catClean = cleanBadgeStr(b.name);
        const nameMatch = (catClean === targetClean || targetClean.includes(catClean) || catClean.includes(targetClean));
        
        let aliasMatch = false;
        if (b.aliases && b.aliases.length > 0) {
          aliasMatch = b.aliases.some(a => cleanBadgeStr(a) === targetClean);
        }

        return nameMatch || aliasMatch;
      });

      let match = null;
      if (candidates.length > 0) {
        match = candidates.find(b => b.cat === detectedSection) || candidates[0];
      }

      if (match) {
        orderQuantities[match.id] = (orderQuantities[match.id] || 0) + qty;
        matchCount++;
        i++;
      } else {
        unmatchedBadges.push(`${qty}x ${line}`);
        i++;
      }
    }
  }

  // 3. Put any unlisted badges into notes
  if (unmatchedBadges.length > 0) {
    const extraBox = document.getElementById("extraBadges");
    const existing = extraBox.value.trim();
    const unlistedText = unmatchedBadges.join("\n");
    extraBox.value = existing ? existing + "\n" + unlistedText : unlistedText;
  }

  renderBadges();
  renderSummary();

  // 4. Hide the upload box now that it has been used
  const dropzone = document.querySelector(".pdf-dropzone");
  if (dropzone) {
    dropzone.style.display = "none";
  }

  // 5. Alert Dialog Box
  if (unmatchedBadges.length > 0) {
    alert(`✅ Loaded ${matchCount} badge(s).\n\n⚠️ ${unmatchedBadges.length} item(s) could not be matched automatically and were added to your notes for the Badge Secretary:\n• ${unmatchedBadges.join("\n• ")}`);
  } else {
    alert(`🎉 Perfect match! Loaded all ${matchCount} badge requirement(s) from your OSM Shopping List.`);
  }

  // 6. Smoothly scroll down specifically to Section 3: Leader & Collection Information
  setTimeout(() => {
    const leaderCard = document.getElementById("leaderDetailsCard");
    if (leaderCard) {
      leaderCard.scrollIntoView({ behavior: "smooth", block: "start" });
    }
  }, 100);
}

function setFilter(cat, elem) {
  currentFilter = cat;
  document.querySelectorAll(".filter-pill").forEach(p => p.classList.remove("active"));
  elem.classList.add("active");
  renderBadges();
}

function renderBadges() {
  const query = (document.getElementById("badgeSearch").value || "").toLowerCase().trim();
  const grid = document.getElementById("badgeGrid");
  grid.innerHTML = "";

  const filtered = CATALOGUE.filter(b => {
    const matchesCat = (currentFilter === "all" || b.cat === currentFilter);
    const matchesQuery = (!query || b.name.toLowerCase().indexOf(query) !== -1);
    return matchesCat && matchesQuery;
  });

  if (filtered.length === 0) {
    grid.innerHTML = '<div style="padding:15px; color:#888; grid-column:1/-1;">No badges found matching that search. You can list them in the "Additional Badges" box below.</div>';
    return;
  }

  filtered.forEach(b => {
    const qty = orderQuantities[b.id] || 0;
    const item = document.createElement("div");
    item.className = "badge-item";
    item.innerHTML = `
      <div class="info">
        <b>${b.name}</b>
        <span>£0.90</span>
      </div>
      <div class="qty-controls">
        <button class="qty-btn" onclick="updateQty('${b.id}', -1)">−</button>
        <span class="qty-num">${qty}</span>
        <button class="qty-btn" onclick="updateQty('${b.id}', 1)">+</button>
      </div>
    `;
    grid.appendChild(item);
  });
}

function updateQty(id, delta) {
  const current = orderQuantities[id] || 0;
  const next = Math.max(0, current + delta);
  if (next === 0) {
    delete orderQuantities[id];
  } else {
    orderQuantities[id] = next;
  }
  renderBadges();
  renderSummary();
}

function getSelectedBadges() {
  const list = [];
  Object.keys(orderQuantities).forEach(id => {
    const badge = CATALOGUE.find(b => b.id === id);
    if (badge && orderQuantities[id] > 0) {
      list.push({
        name: badge.name,
        quantity: orderQuantities[id],
        unitPrice: BADGE_PRICE,
        lineTotal: (orderQuantities[id] * BADGE_PRICE).toFixed(2)
      });
    }
  });
  return list;
}

function renderSummary() {
  const items = getSelectedBadges();
  const container = document.getElementById("selectedTableContainer");
  const payButtons = document.getElementById("payment-buttons");
  const cardBtn = document.getElementById("cardBtn");

  if (items.length === 0) {
    container.innerHTML = '<p style="color:var(--text-muted); font-size:14px;">No badges selected yet. Drop an OSM PDF above or use the <b>+</b> buttons.</p>';
    payButtons.style.display = "none";
    return;
  }

  let totalQty = 0;
  let grandTotal = 0;
  let rows = items.map(b => {
    totalQty += b.quantity;
    grandTotal += parseFloat(b.lineTotal);
    return `<tr>
      <td><b>${b.name}</b></td>
      <td class="text-right">${b.quantity}</td>
      <td class="text-right">£${b.unitPrice.toFixed(2)}</td>
      <td class="text-right">£${b.lineTotal}</td>
    </tr>`;
  }).join("");

  container.innerHTML = `
    <table>
      <tr><th>Badge Name</th><th class="text-right">Qty</th><th class="text-right">Price</th><th class="text-right">Total</th></tr>
      ${rows}
      <tr style="background:#fafafa; font-weight:bold;">
        <td>Total (${totalQty} badges)</td>
        <td class="text-right">${totalQty}</td>
        <td></td>
        <td class="text-right">£${grandTotal.toFixed(2)}</td>
      </tr>
    </table>
  `;

  cardBtn.innerText = `💳 Pay £${grandTotal.toFixed(2)} with Card / Apple Pay`;
  payButtons.style.display = "block";
}

function validateLeader() {
  const name = document.getElementById("leaderName").value.trim();
  const email = document.getElementById("leaderEmail").value.trim();
  const group = document.getElementById("leaderGroup").value;
  const section = document.getElementById("leaderSection").value;
  const items = getSelectedBadges();

  const emailRegex = /^[^\s@]+@[^\s@]+\.[^\s@]+$/;
  if (!name) {
    alert("Please enter your Leader Name.");
    return false;
  }
  if (!email || !emailRegex.test(email)) {
    alert("Please enter a valid, complete email address (e.g. name@group.org.uk).");
    return false;
  }
  if (!group) {
    alert("Please select your Scout Group / Unit.");
    return false;
  }
  if (items.length === 0 && !document.getElementById("extraBadges").value.trim()) {
    alert("Please select at least one badge or specify badges in the additional box.");
    return false;
  }

  return {
    leaderName: name,
    leaderEmail: email,
    leaderGroup: `${group} - ${section}`,
    leaderNotes: document.getElementById("leaderNotes").value.trim() || "No specific date/urgency specified",
    extraBadges: document.getElementById("extraBadges").value.trim()
  };
}

async function sendEmailNotification(paymentType, leaderInfo, items, grandTotal) {
  let pickingList = items.map(i => `${i.quantity}x ${i.name} = £${i.lineTotal}`).join("\n");
  if (leaderInfo.extraBadges) {
    pickingList += `\n\nEXTRA / UNLISTED BADGES REQUESTED:\n${leaderInfo.extraBadges}`;
  }

  const bacsDetails = (paymentType.indexOf("BACS") !== -1)
    ? `\nBACS INSTRUCTIONS FOR GROUP TREASURER:\nAccount Name  : ${DISTRICT_BANK.accountName}\nSort Code     : ${DISTRICT_BANK.sortCode}\nAccount Number: ${DISTRICT_BANK.accountNumber}\nPayment Ref   : #${orderRef}\n`
    : "";

  const bodyText =
    `ARROW DISTRICT SCOUT SHOP - BADGE ORDER\n` +
    `----------------------------------------\n` +
    `Order Ref     : #${orderRef}\n` +
    `Date          : ${new Date().toLocaleDateString("en-GB")}\n` +
    `Status        : ${paymentType}\n\n` +
    `LEADER & COLLECTION DETAILS (NO DELIVERY):\n` +
    `Leader Name   : ${leaderInfo.leaderName}\n` +
    `Group/Section : ${leaderInfo.leaderGroup}\n` +
    `Leader Email  : ${leaderInfo.leaderEmail}\n` +
    `Collection / Urgency Note: ${leaderInfo.leaderNotes}\n\n` +
    `PICKING LIST:\n` +
    pickingList + `\n` +
    `----------------------------------------\n` +
    `Grand Total   : £${grandTotal.toFixed(2)}\n` +
    `----------------------------------------\n` +
    bacsDetails + `\n` +
    (paymentType.indexOf("BACS") !== -1
      ? "ACTION: Badge Secretary to verify BACS transfer before releasing badges."
      : "CONFIRMED: Paid online via SumUp card payment.");

  try {
    await fetch("https://api.web3forms.com/submit", {
      method: "POST",
      headers: { "Content-Type": "application/json", "Accept": "application/json" },
      body: JSON.stringify({
        access_key: WEB3FORMS_KEY,
        subject: `[Badge Order] #${orderRef} - ${leaderInfo.leaderGroup} (${paymentType})`,
        from_name: "Arrow District Badge Shop",
        name: leaderInfo.leaderName,
        email: leaderInfo.leaderEmail,
        message: bodyText
      })
    });
  } catch (err) {
    console.error("Web3Forms error:", err);
  }
}

